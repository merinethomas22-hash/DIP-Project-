# IoU (Jaccard Index)
def calculate_iou(true_mask, predicted_mask):
    true_mask = true_mask > 0
    predicted_mask = predicted_mask > 0

    intersection = np.logical_and(true_mask, predicted_mask).sum()
    union = np.logical_or(true_mask, predicted_mask).sum()

    if union == 0:
        return 1.0

    return intersection / union


# Dice Score
def calculate_dice(true_mask, predicted_mask):
    true_mask = true_mask > 0
    predicted_mask = predicted_mask > 0

    intersection = np.logical_and(true_mask, predicted_mask).sum()

    total = true_mask.sum() + predicted_mask.sum()

    if total == 0:
        return 1.0

    return (2 * intersection) / total


# Pixel Accuracy
def calculate_accuracy(true_mask, predicted_mask):
    true_mask = true_mask > 0
    predicted_mask = predicted_mask > 0

    correct_pixels = np.sum(true_mask == predicted_mask)
    total_pixels = true_mask.size

    return correct_pixels / total_pixels


