for image_file, mask_file in pairs:

    # Read original image
    image = cv2.imread(os.path.join(test_path, image_file))

    # Read ground-truth mask
    true_mask = cv2.imread(
        os.path.join(test_path, mask_file),
        cv2.IMREAD_GRAYSCALE
    )

    # Make sure both have same size
    if image.shape[:2] != true_mask.shape[:2]:
        true_mask = cv2.resize(
            true_mask,
            (image.shape[1], image.shape[0]),
            interpolation=cv2.INTER_NEAREST
        )

    # Convert image to grayscale
    gray = cv2.cvtColor(image, cv2.COLOR_BGR2GRAY)

    # ==================================================
    # METHOD 1: OTSU THRESHOLDING
    # ==================================================

    _, otsu_mask = cv2.threshold(
        gray,
        0,
        255,
        cv2.THRESH_BINARY + cv2.THRESH_OTSU
    )

    # ==================================================
    # METHOD 2: HSV COLOR THRESHOLDING
    # ==================================================

    hsv = cv2.cvtColor(image, cv2.COLOR_BGR2HSV)

    lower1 = np.array([0, 50, 40])
    upper1 = np.array([20, 255, 255])

    lower2 = np.array([160, 50, 40])
    upper2 = np.array([180, 255, 255])

    mask1 = cv2.inRange(hsv, lower1, upper1)
    mask2 = cv2.inRange(hsv, lower2, upper2)

    hsv_mask = cv2.bitwise_or(mask1, mask2)

    # Morphological processing
    kernel = np.ones((5, 5), np.uint8)

    hsv_mask = cv2.morphologyEx(
        hsv_mask,
        cv2.MORPH_OPEN,
        kernel
    )

    hsv_mask = cv2.morphologyEx(
        hsv_mask,
        cv2.MORPH_CLOSE,
        kernel
    )

    # ==================================================
    # Calculate metrics
    # ==================================================

    otsu_iou = calculate_iou(true_mask, otsu_mask)
    otsu_dice = calculate_dice(true_mask, otsu_mask)
    otsu_accuracy = calculate_accuracy(true_mask, otsu_mask)

    hsv_iou = calculate_iou(true_mask, hsv_mask)
    hsv_dice = calculate_dice(true_mask, hsv_mask)
    hsv_accuracy = calculate_accuracy(true_mask, hsv_mask)

    # Store results
    results.append({
        "Image": image_file,

        "Otsu IoU": otsu_iou,
        "Otsu Dice": otsu_dice,
        "Otsu Accuracy": otsu_accuracy,

        "HSV IoU": hsv_iou,
        "HSV Dice": hsv_dice,
        "HSV Accuracy": hsv_accuracy
    })


